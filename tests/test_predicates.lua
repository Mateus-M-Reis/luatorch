local torch = require("torch")

local nan = 0 / 0

test("isnan finds only NaN", function()
  local t = torch.tensor({ nan, 1, math.huge, -math.huge })
  local mask = torch.isnan(t)
  assert_dtype(mask, "bool")
  assert_tensor(mask, { true, false, false, false })
end)

test("isinf finds both infinities", function()
  local t = torch.tensor({ nan, 1, math.huge, -math.huge })
  local mask = torch.isinf(t)
  assert_dtype(mask, "bool")
  assert_tensor(mask, { false, false, true, true })
end)

test("Tensor methods match module functions", function()
  local t = torch.tensor({ nan, math.huge, 0 })
  assert_tensor(t:isnan(), torch.isnan(t):totable())
  assert_tensor(t:isinf(), torch.isinf(t):totable())
end)

test("predicates preserve 2-D shape", function()
  local t = torch.tensor({ { nan, 1 }, { math.huge, 2 } })
  assert_shape(torch.isnan(t), { 2, 2 })
  assert_tensor(torch.isnan(t), { { true, false }, { false, false } })
  assert_tensor(torch.isinf(t), { { false, false }, { true, false } })
end)

test("0-dim predicates", function()
  assert_true(torch.isnan(torch.tensor(nan)):item())
  assert_false(torch.isnan(torch.tensor(1)):item())
  assert_true(torch.isinf(torch.tensor(math.huge)):item())
  assert_false(torch.isinf(torch.tensor(nan)):item())
end)

test("integer and boolean tensors are never NaN or Inf", function()
  local ints = torch.tensor({ 1, 0, -1 }, { dtype = torch.int64 })
  assert_tensor(torch.isnan(ints), { false, false, false })
  assert_tensor(torch.isinf(ints), { false, false, false })
  local bools = torch.tensor({ true, false })
  assert_tensor(torch.isnan(bools), { false, false })
  assert_tensor(torch.isinf(bools), { false, false })
end)

test("float16 predicates", function()
  local t = torch.tensor({ nan, math.huge, 1.5 }, { dtype = torch.float16 })
  assert_dtype(torch.isnan(t), "bool")
  assert_tensor(torch.isnan(t), { true, false, false })
  assert_tensor(torch.isinf(t), { false, true, false })
end)

test("empty tensors", function()
  assert_tensor(torch.isnan(torch.zeros(0)), {})
  assert_tensor(torch.isinf(torch.zeros(0)), {})
end)

test("predicates do not modify the input", function()
  local t = torch.tensor({ nan, math.huge, 1 })
  torch.isnan(t)
  torch.isinf(t)
  assert_true(t:get(1) ~= t:get(1))
  assert_eq(t:get(2), math.huge)
  assert_eq(t:get(3), 1)
end)

test("non-tensor arguments are rejected", function()
  assert_error(function()
    torch.isnan({ 1, 2 })
  end, "expects a tensor")
  assert_error(function()
    torch.isinf({ 1, 2 })
  end, "expects a tensor")
end)

test("isfinite accepts ordinary values only", function()
  local t = torch.tensor({ nan, 1, math.huge, -math.huge, -0.0 })
  local mask = torch.isfinite(t)
  assert_dtype(mask, "bool")
  assert_tensor(mask, { false, true, false, false, true })
  assert_tensor(t:isfinite(), torch.isfinite(t):totable())
end)

test("isfinite preserves shape and handles 0-dim", function()
  local t = torch.tensor({ { nan, 1 }, { math.huge, 2 } })
  assert_shape(torch.isfinite(t), { 2, 2 })
  assert_tensor(torch.isfinite(t), { { false, true }, { false, true } })
  assert_true(torch.isfinite(torch.tensor(1)):item())
  assert_false(torch.isfinite(torch.tensor(nan)):item())
  assert_false(torch.isfinite(torch.tensor(math.huge)):item())
end)

test("isfinite on integer, bool, and float16 tensors", function()
  local ints = torch.tensor({ 1, 0, -1 }, { dtype = torch.int64 })
  assert_tensor(torch.isfinite(ints), { true, true, true })
  local bools = torch.tensor({ true, false })
  assert_tensor(torch.isfinite(bools), { true, true })
  local half = torch.tensor({ nan, math.huge, 1.5 },
    { dtype = torch.float16 })
  assert_tensor(torch.isfinite(half), { false, false, true })
  local empty = torch.zeros(0)
  assert_tensor(torch.isfinite(empty), {})
end)

test("isfinite rejects non-tensors", function()
  assert_error(function()
    torch.isfinite({ 1, 2 })
  end, "expects a tensor")
end)

test("predicates detach from autograd", function()
  local x = torch.tensor({ nan, 1, math.huge }, { requires_grad = true })
  for _, predicate in ipairs({ torch.isnan, torch.isinf, torch.isfinite }) do
    local mask = predicate(x)
    assert_dtype(mask, "bool")
    assert_false(mask:requires_grad())
    assert_error(function()
      mask:sum():backward()
    end, "does not require grad")
  end
  assert_true(x:requires_grad())
  assert_eq(x:has_grad(), false)
end)

test("isfinite masks compose with autograd", function()
  local x = torch.tensor({ 1, nan, math.huge, 4 },
    { requires_grad = true })
  local finite = torch.isfinite(x)
  local safe = torch.where(finite, x, torch.zeros(4))
  safe:sum():backward()
  assert_tensor(x:grad(), { 1, 0, 0, 1 })

  local y = torch.tensor({ 1, 0 / 0, 3 }, { requires_grad = true })
  local selected = y[torch.isfinite(y)]
  assert_tensor(selected, { 1, 3 })
  selected:sum():backward()
  assert_tensor(y:grad(), { 1, 0, 1 })
end)
