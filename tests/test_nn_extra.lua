end)

test("new layers survive state_dict roundtrips", function()
  local model = nn.Sequential(
    nn.LayerNorm(4),
    nn.Linear(4, 3))
  local path = os.tmpname() .. ".luatorch"
  model:save(path)
  local restored = nn.Sequential(nn.LayerNorm(4), nn.Linear(4, 3))
  restored:load(path)
