test("MSELoss uses the fused reduction and backpropagates", function()
  local nn = require("torch.nn")
  local criterion = nn.MSELoss("mean")
  local prediction = torch.randn(64):requires_grad_(true)
  local target = torch.randn(64)
  local reference = prediction:detach():clone():requires_grad_(true)

  local loss = criterion(prediction, target)
  local expected = ((reference - target) ^ 2):mean()
  assert_true(loss:allclose(expected, 1e-5, 1e-6))
  assert_true(criterion._fused ~= nil)
  loss:backward()
  expected:backward()
  assert_true(prediction:grad():allclose(reference:grad(), 1e-5, 1e-6))
end)

test("L1Loss uses the fused reduction and backpropagates", function()
  local nn = require("torch.nn")
