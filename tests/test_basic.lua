local torch = require("torch")

test("tensor from nested table", function()
  local t = torch.tensor({ { 1, 2 }, { 3, 4 } })
  assert_shape(t, { 2, 2 })
  assert_dtype(t, "float32")
  assert_tensor(t, { { 1, 2 }, { 3, 4 } })
end)

test("tensor from flat table", function()
  local t = torch.tensor({ 1.5, -2.5, 3 })
  assert_shape(t, { 3 })
  assert_tensor(t, { 1.5, -2.5, 3 })
end)

test("explicit integer dtype", function()
  local t = torch.tensor({ 1, 2, 3 }, { dtype = torch.int64 })
  assert_dtype(t, "int64")
  assert_tensor(t, { 1, 2, 3 })
  assert_eq(t:element_size(), 8)
end)

test("boolean inference", function()
  local t = torch.tensor({ true, false, true })
  assert_dtype(t, "bool")
  assert_tensor(t, { true, false, true })
  assert_eq(t:element_size(), 1)
end)

test("scalar tensors", function()
  local float = torch.tensor(2.5)
  assert_eq(float:dim(), 0)
  assert_dtype(float, "float32")
  assert_near(float:item(), 2.5)

  local boolean = torch.tensor(true)
  assert_eq(boolean:dim(), 0)
  assert_dtype(boolean, "bool")
  assert_eq(boolean:item(), true)
end)

test("zeros / ones / full", function()
  local zeros = torch.zeros(2, 3)
  assert_shape(zeros, { 2, 3 })
  assert_near(zeros:sum():item(), 0)
  assert_eq(zeros:numel(), 6)

  local ones = torch.ones({ 3, 2 }, { dtype = torch.float64 })
  assert_dtype(ones, "float64")
  assert_near(ones:sum():item(), 6)

  local full = torch.full({ 2, 2 }, 7)
  assert_tensor(full, { { 7, 7 }, { 7, 7 } })
end)

test("eye", function()
  local t = torch.eye(3)
  assert_shape(t, { 3, 3 })
  assert_tensor(t, { { 1, 0, 0 }, { 0, 1, 0 }, { 0, 0, 1 } })
end)

test("arange", function()
  local t = torch.arange(5)
  assert_dtype(t, "int64")
  assert_tensor(t, { 0, 1, 2, 3, 4 })

  local stepped = torch.arange(1, 10, 2)
  assert_tensor(stepped, { 1, 3, 5, 7, 9 })

  local floats = torch.arange(0, 1, 0.25)
  assert_dtype(floats, "float32")
  assert_near(floats:totable(), { 0, 0.25, 0.5, 0.75 })
end)

test("linspace", function()
  local t = torch.linspace(0, 1, 5)
  assert_near(t:totable(), { 0, 0.25, 0.5, 0.75, 1 })
end)

test("rand / randn / randperm", function()
  local uniform = torch.rand(100)
  assert_eq(uniform:dim(), 1)
  assert_true(uniform:min():item() >= 0)
  assert_true(uniform:max():item() < 1)

  local normal = torch.randn(10, 10)
  assert_shape(normal, { 10, 10 })

  local permutation = torch.randperm(10)
  assert_shape(permutation, { 10 })
  assert_eq(permutation:sum():item(), 45)
end)

test("Torch7-style constructors", function()
  local empty = torch.Tensor(2, 3)
  assert_shape(empty, { 2, 3 })
  assert_dtype(empty, "float32")

  local values = torch.Tensor({ 1, 2, 3 })
  assert_dtype(values, "float32")
  assert_tensor(values, { 1, 2, 3 })

  local longs = torch.LongTensor({ 4, 5 })
  assert_dtype(longs, "int64")
  assert_tensor(longs, { 4, 5 })

  local doubles = torch.DoubleTensor({ 1.5, 2.5 })
  assert_dtype(doubles, "float64")
  assert_tensor(doubles, { 1.5, 2.5 })

  -- A bare number is a length, as in Torch7; scalars use torch.tensor.
  local vector = torch.LongTensor(5)
  assert_shape(vector, { 5 })
  assert_dtype(vector, "int64")
  assert_shape(torch.Tensor(5), { 5 })
  assert_eq(torch.tensor(5):dim(), 0)
end)

test("dtype conversion", function()
  local t = torch.tensor({ 1.9, -2.9, 0 })
  local ints = t:to(torch.int64)
  assert_dtype(ints, "int64")
  assert_tensor(ints, { 1, -2, 0 })

  local back = ints:to(torch.float32)
  assert_dtype(back, "float32")
  assert_tensor(back, { 1, -2, 0 })
end)

test("boolean conversion", function()
  local t = torch.tensor({ 0, 1, -3 })
  local mask = t:to(torch.bool)
  assert_tensor(mask, { false, true, true })
end)

test("float16 roundtrip", function()
  local t = torch.tensor({ 1.5, 2.5 }):to(torch.float16)
  assert_dtype(t, "float16")
  assert_eq(t:element_size(), 2)
  assert_near(t:to(torch.float32):totable(), { 1.5, 2.5 })
end)

test("clone is independent", function()
  local original = torch.tensor({ 1, 2, 3 })
  local copy = original:clone()
  copy:set(1, 99)
  assert_tensor(original, { 1, 2, 3 })
  assert_tensor(copy, { 99, 2, 3 })

  local detached = original:detach()
  assert_tensor(detached, { 1, 2, 3 })
end)

test("type names", function()
  assert_eq(torch.tensor({ 1 }):type(), "torch.FloatTensor")
  assert_eq(torch.LongTensor({ 1 }):type(), "torch.LongTensor")
  assert_eq(torch.BoolTensor({ true }):type(), "torch.BoolTensor")
end)

test("metadata", function()
  local t = torch.zeros(2, 3, 4)
  assert_eq(t:dim(), 3)
  assert_eq(t:numel(), 24)
  assert_eq(t:nbytes(), 96)
  assert_eq(t:size(1), 2)
  assert_eq(t:size(-1), 4)
  assert_shape(t, { 2, 3, 4 })
  assert_true(t:is_contiguous())
  assert_true(t:is_floating_point())
  assert_false(t:requires_grad())
  assert_eq(t:device(), "cpu")
  assert_false(t:is_cuda())
end)

test("get and set", function()
  local t = torch.zeros(2, 3)
  t:set(1, 2, 5)
  t:set(2, 3, 7)
  assert_eq(t:get(1, 2), 5)
  assert_eq(t:get(2, 3), 7)
  assert_eq(t[1][2]:item(), 5)

  local matrix = torch.tensor({ { 1, 2 }, { 3, 4 } })
  matrix[1][2] = 9
  assert_eq(matrix:get(1, 2), 9)
  matrix[2] = torch.tensor({ 7, 8 })
  assert_tensor(matrix, { { 1, 9 }, { 7, 8 } })
end)

test("negative indices", function()
  local t = torch.tensor({ 10, 20, 30 })
  assert_eq(t:get(-1), 30)
  assert_eq(t:get(-3), 10)
  assert_eq(t:select(1, -1):item(), 30)
end)

test("item", function()
  local t = torch.tensor(4.5)
  assert_near(t:item(), 4.5)
  local one = torch.tensor({ 7 })
  assert_eq(one:item(), 7)
  assert_error(function()
    torch.zeros(2):item()
  end, "exactly one element")
end)

test("global default dtype", function()
  local previous = torch.get_default_dtype()
  local ok, err = pcall(function()
    torch.set_default_dtype(torch.float64)
    assert_dtype(torch.zeros(2), "float64")
    assert_dtype(torch.randn(2), "float64")
    assert_dtype(torch.eye(2), "float64")
  end)
  torch.set_default_dtype(previous)
  if not ok then
    error(err, 2)
  end
  assert_eq(torch.get_default_dtype(), previous)
end)

test("constructors accept requires_grad", function()
  local t = torch.zeros(2, 3, { requires_grad = true })
  assert_true(t:requires_grad())
  assert_shape(t, { 2, 3 })
end)
