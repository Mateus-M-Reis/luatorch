local torch = require("torch")

local function integer_matrix()
  return torch.arange(1, 13):reshape(3, 4)
end

test("sum", function()
  local t = integer_matrix()
  assert_eq(t:sum():item(), 78)
  assert_tensor(t:sum(1), { 15, 18, 21, 24 })
  assert_tensor(t:sum(2), { 10, 26, 42 })
  assert_tensor(t:sum(-1), { 10, 26, 42 })
  assert_shape(t:sum(1, true), { 1, 4 })
  assert_shape(t:sum(2, true), { 3, 1 })
  assert_eq(t:sum():dim(), 0)
end)

test("mean", function()
  local t = integer_matrix():to(torch.float32)
  assert_near(t:mean():item(), 6.5)
  assert_near(t:mean(1):totable(), { 5, 6, 7, 8 })
  assert_near(t:mean(2):totable(), { 2.5, 6.5, 10.5 })
  assert_shape(t:mean(2, true), { 3, 1 })
end)

test("prod", function()
  local t = torch.arange(1, 5)
  assert_eq(t:prod():item(), 24)
  assert_tensor(t:reshape(2, 2):prod(1), { 3, 8 })
  assert_tensor(t:reshape(2, 2):prod(2), { 2, 12 })
end)

test("max and min", function()
  local t = integer_matrix()
  assert_eq(t:max():item(), 12)
  assert_eq(t:min():item(), 1)
  assert_tensor(t:max(1), { 9, 10, 11, 12 })
  assert_tensor(t:max(2), { 4, 8, 12 })
  assert_tensor(t:min(1), { 1, 2, 3, 4 })
  assert_tensor(t:min(2), { 1, 5, 9 })
  assert_shape(t:max(1, true), { 1, 4 })
end)

test("max and min also return indices", function()
  local t = integer_matrix()
  local values, indices = t:max(1)
  assert_tensor(values, { 9, 10, 11, 12 })
  assert_tensor(indices, { 3, 3, 3, 3 })

  local min_values, min_indices = t:min(2)
  assert_tensor(min_values, { 1, 5, 9 })
  assert_tensor(min_indices, { 1, 1, 1 })
end)

test("argmax and argmin are 1-based", function()
  local t = integer_matrix()
  assert_tensor(t:argmax(1), { 3, 3, 3, 3 })
  assert_tensor(t:argmax(2), { 4, 4, 4 })
  assert_tensor(t:argmin(1), { 1, 1, 1, 1 })
  assert_tensor(t:argmin(2), { 1, 1, 1 })
  assert_eq(t:argmax():item(), 12)
  assert_eq(t:argmin():item(), 1)
end)

test("variance and stddev", function()
  local t = torch.tensor({ 1, 2, 3, 4 })
  assert_near(t:var():item(), 5 / 3, 1e-6)
  assert_near(t:var(nil, false):item(), 1.25, 1e-6)
  assert_near(t:std():item(), math.sqrt(5 / 3), 1e-6)

  local matrix = torch.tensor({ { 1, 2 }, { 3, 4 } })
  assert_near(matrix:var(1):totable(), { 2, 2 })
  assert_near(matrix:var(2):totable(), { 0.5, 0.5 })
end)

test("norm", function()
  local t = integer_matrix()
  assert_near(t:norm(1):item(), 78)
  assert_near(t:norm(2):item(), math.sqrt(650), 1e-4)
  assert_near(t:norm(math.huge):item(), 12)
  assert_near(t:norm(1, 1):totable(), { 15, 18, 21, 24 })
  assert_near(t:norm(2, 1):totable(), { math.sqrt(107), math.sqrt(140), math.sqrt(179), math.sqrt(224) }, 1e-4)
end)

test("cumulative ops", function()
  local t = torch.tensor({ 1, 2, 3, 4 })
  assert_tensor(t:cumsum(1), { 1, 3, 6, 10 })
  assert_tensor(t:cumprod(1), { 1, 2, 6, 24 })
  local matrix = torch.tensor({ { 1, 2 }, { 3, 4 } })
  assert_tensor(matrix:cumsum(1), { { 1, 2 }, { 4, 6 } })
  assert_tensor(matrix:cumsum(2), { { 1, 3 }, { 3, 7 } })
end)

test("all and any", function()
  assert_eq(torch.tensor({ true, true }):all():item(), true)
  assert_eq(torch.tensor({ true, false }):all():item(), false)
  assert_eq(torch.tensor({ false, false }):any():item(), false)
  assert_eq(torch.tensor({ false, true }):any():item(), true)
  assert_tensor(torch.tensor({ { true, false }, { true, true } }):all(2), { false, true })
  assert_tensor(torch.tensor({ { true, false }, { false, false } }):any(2), { true, false })
end)

test("median handles odd, even, and dimension cases", function()
  assert_eq(torch.tensor({1, 3, 2}):median(), 2)
  assert_eq(torch.tensor({1, 2, 3, 4}):median(), 2.5)
  local values = torch.tensor({{1, 2}, {3, 4}}):median(2)
  assert_shape(values, { 2, 1 })
  assert_eq(values:get(1, 1), 1.5)
  assert_eq(values:get(2, 1), 3.5)
end)
