local torch = require("torch")

test("ragged tables are rejected", function()
  assert_error(function()
    torch.tensor({ { 1, 2 }, { 3 } })
  end, "rectangular")
end)

test("unknown dtype", function()
  assert_error(function()
    torch.zeros(2, { dtype = "complex64" })
  end, "unknown dtype")
end)

test("dimension zero is rejected", function()
  local t = torch.zeros(2, 2)
  assert_error(function()
    t:sum(0)
  end, "1-based")
end)

test("index zero is rejected", function()
  local t = torch.tensor({ 1, 2, 3 })
  assert_error(function()
    t:get(0)
  end, "index 0")
end)

test("out-of-range index", function()
  local t = torch.tensor({ 1, 2, 3 })
  assert_error(function()
    t:get(4)
  end, "out of range")
end)

test("wrong number of indices", function()
  local t = torch.zeros(2, 3)
  assert_error(function()
    t:get(1)
  end, "expected 2 indices")
end)

test("incompatible shapes", function()
  local a = torch.ones(2, 2)
  local b = torch.ones(3)
  assert_error(function()
    a:add(b)
  end)
end)

test("empty concatenation", function()
  assert_error(function()
    torch.cat({})
  end, "non-empty")
end)

test("mean of an integer tensor", function()
  local t = torch.LongTensor({ 1, 2, 3 })
  assert_error(function()
    t:mean()
  end)
end)

test("unsupported device", function()
  assert_error(function()
    torch.zeros(2, { device = "cuda" })
  end, "CPU")
end)

test("float16 from a table", function()
  assert_error(function()
    torch.tensor({ 1 }, { dtype = torch.float16 })
  end, "float16")
end)

test("bad matrix shapes", function()
  local a = torch.ones(2, 2)
  local b = torch.ones(3, 3)
  assert_error(function()
    a:mm(b)
  end)
end)

test("non-tensor arguments", function()
  local t = torch.zeros(2)
  assert_error(function()
    t:add("nope")
  end, "Tensor or a number")
  assert_error(function()
    torch.cat({ t, 5 })
  end, "tensors")
end)

test("reshape with incompatible sizes", function()
  local t = torch.zeros(6)
  assert_error(function()
    t:view(4, 2)
  end)
end)

test("set on a 0-dim tensor", function()
  local t = torch.tensor(1.0)
  assert_error(function()
    t:set(1, 2)
  end)
end)

test("indexing beyond dimensions", function()
  local t = torch.zeros(3)
  assert_error(function()
    local _ = t[1][1]
  end)
end)

test("mixed booleans and numbers", function()
  assert_error(function()
    torch.tensor({ true, 1 })
  end, "mix")
end)
